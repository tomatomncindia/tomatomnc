// One-shot generator: reads world-atlas topojson and emits an optimized
// SVG path string for inlining. Projects the inhabited world (Antarctica
// removed) to a tight viewBox using equal-earth projection so the populated
// continents fill the frame, and projects market coordinates to match.
import fs from "node:fs";
import path from "node:path";
import { feature } from "topojson-client";
import { geoEqualEarth, geoPath } from "d3-geo";

const TOPO_PATH = process.argv[2] || "scripts/world-topo.json";
const OUT_PATH = path.resolve(
  process.cwd(),
  "src/components/sections/world-map-path.ts",
);

const topo = JSON.parse(fs.readFileSync(TOPO_PATH, "utf8"));
const all = feature(topo, topo.objects.countries);

// Drop Antarctica (id 010) and the Fr. Southern Antarctic Lands (id 260):
// irrelevant to a distribution map and they add a wide empty band at the
// bottom that squashes the inhabited world. Result fills the frame edge-to-edge.
const EXCLUDE = new Set(["010", "260"]);
const land = {
  type: "FeatureCollection",
  features: all.features.filter((f) => !EXCLUDE.has(String(f.id))),
};

// Equal-earth projection. Fit to a 1000-wide box, then derive a tight height
// from the projected bounds so there is no dead vertical space. PAD keeps a
// thin breathing margin inside the frame.
const W = 1000;
const PAD = 6;
const projection = geoEqualEarth();
projection.fitWidth(W - PAD * 2, land);

const pathGen = geoPath(projection);

// Translate so the land bbox sits at [PAD, PAD], then size the viewBox to it.
let [[bx0, by0], [bx1, by1]] = pathGen.bounds(land);
const [tx, ty] = projection.translate();
projection.translate([tx - bx0 + PAD, ty - by0 + PAD]);
[[bx0, by0], [bx1, by1]] = pathGen.bounds(land);
const H = Math.round(by1 + PAD);

// Equator + prime-meridian guide positions in projected space.
const [meridianX, equatorY] = projection([0, 0]).map((n) =>
  Number(n.toFixed(1)),
);

// Single combined land path for all remaining countries
const d = pathGen(land);

// Round path coords to 1 decimal for smaller output without visible quality loss
const rounded = d
  .replace(/\d+\.\d+/g, (n) => Number(parseFloat(n).toFixed(1)).toString())
  .replace(/-0\b/g, "0");

// Markets with their [lon, lat]. Region tags match REGIONS in data/markets.ts.
const MARKETS_RAW = [
  // North & South America
  ["United States", "North & South America", -98.0, 38.0],
  ["Canada", "North & South America", -106.0, 56.0],
  ["Mexico", "North & South America", -102.0, 23.0],
  ["Brazil", "North & South America", -52.0, -10.0],
  ["Andean Region", "North & South America", -75.0, -10.0],
  ["Argentina", "North & South America", -64.0, -34.0],
  // Europe
  ["United Kingdom", "Europe", -2.0, 54.0],
  ["Germany", "Europe", 10.5, 51.0],
  ["France", "Europe", 2.5, 47.0],
  ["Spain", "Europe", -3.7, 40.0],
  ["Italy", "Europe", 12.5, 42.5],
  ["Poland", "Europe", 19.5, 52.0],
  ["Russia (West)", "Europe", 40.0, 57.0],
  ["Turkey", "Europe", 35.0, 39.0],
  // MENA
  ["UAE", "Middle East & North Africa", 54.0, 24.0],
  ["Saudi Arabia", "Middle East & North Africa", 45.0, 24.0],
  ["Egypt", "Middle East & North Africa", 30.0, 27.0],
  ["Morocco", "Middle East & North Africa", -7.0, 32.0],
  ["Lebanon", "Middle East & North Africa", 35.8, 33.9],
  ["Jordan", "Middle East & North Africa", 36.5, 31.5],
  // East Asia
  ["South Korea", "East Asia", 127.8, 36.5],
  ["Japan", "East Asia", 138.0, 36.0],
  ["China", "East Asia", 104.0, 35.0],
  ["Taiwan", "East Asia", 121.0, 23.7],
  ["Hong Kong", "East Asia", 114.2, 22.3],
  // Southeast Asia
  ["Vietnam", "Southeast Asia", 108.0, 16.0],
  ["Thailand", "Southeast Asia", 101.0, 15.0],
  ["Malaysia", "Southeast Asia", 102.0, 4.0],
  ["Indonesia", "Southeast Asia", 113.0, -2.5],
  ["Philippines", "Southeast Asia", 122.0, 13.0],
  ["Singapore", "Southeast Asia", 103.8, 1.4],
  ["Myanmar", "Southeast Asia", 96.0, 21.0],
  // Rest of World
  ["South Africa", "Rest of World", 25.0, -29.0],
  ["India", "Rest of World", 78.0, 22.0],
  ["Australia", "Rest of World", 134.0, -25.0],
  ["New Zealand", "Rest of World", 172.0, -41.0],
];

const markets = MARKETS_RAW.map(([name, region, lon, lat]) => {
  const [x, y] = projection([lon, lat]);
  return {
    name,
    region,
    x: Number(x.toFixed(1)),
    y: Number(y.toFixed(1)),
  };
});

// Korea HQ — same projection used elsewhere
const [hqX, hqY] = projection([127.0769, 37.0]);
const hq = { x: Number(hqX.toFixed(1)), y: Number(hqY.toFixed(1)) };

const out = `// Auto-generated by scripts/gen-world-map.mjs — do not edit by hand.
// Source: world-atlas@2 (countries-110m), equal-earth projection, Antarctica removed.
// Single combined land path string plus market markers projected to the same coords.

export const WORLD_PATH = ${JSON.stringify(rounded)};
export const WORLD_VIEWBOX = "0 0 ${W} ${H}";
export const WORLD_WIDTH = ${W};
export const WORLD_HEIGHT = ${H};

// Guide-line positions (equal-earth places these dynamically based on the fit).
export const EQUATOR_Y = ${equatorY};
export const MERIDIAN_X = ${meridianX};

export type ProjectedMarket = {
  name: string;
  region: string;
  x: number;
  y: number;
};

export const PROJECTED_MARKETS: ProjectedMarket[] = ${JSON.stringify(markets, null, 2)};

export const HQ = ${JSON.stringify(hq)};
`;

fs.writeFileSync(OUT_PATH, out);
console.log(
  `Wrote ${OUT_PATH} — ${(out.length / 1024).toFixed(1)} KB (path: ${(rounded.length / 1024).toFixed(1)} KB, ${markets.length} markets)`,
);
