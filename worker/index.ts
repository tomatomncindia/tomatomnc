/**
 * Custom Worker entry (wrangler.jsonc → main). Wraps the OpenNext worker so
 * /videos/* can be served with HTTP Range support; everything else goes to
 * OpenNext unchanged. Pattern from the OpenNext docs ("Custom Worker").
 *
 * Only /videos/* reaches this code before the asset layer (see
 * assets.run_worker_first). That path returns before OpenNext's middleware
 * and its lazily imported ~2 MB server handler, so it doesn't add the
 * cold-start cost described in the README (Error 1102).
 *
 * Excluded from the Next tsconfig: `.open-next/worker.js` only exists after
 * `opennextjs-cloudflare build`, and Next type-checks before that step.
 */
// Generated by `opennextjs-cloudflare build`.
import openNext from "../.open-next/worker.js";
import { serveWithRanges } from "./video-range";
// Byte sizes of public/videos/*, written by `node scripts/encode-videos.mjs`.
import videoSizes from "./video-sizes.json";

type Env = { ASSETS: { fetch(request: Request): Promise<Response> } };

const worker = {
  async fetch(request: Request, env: Env, ctx: unknown) {
    const { pathname } = new URL(request.url);
    if (pathname.startsWith("/videos/")) {
      const size = (videoSizes as Record<string, number>)[pathname];
      return serveWithRanges(request, env.ASSETS, size);
    }
    return openNext.fetch(request, env, ctx);
  },
};

export default worker;

// Re-export OpenNext's Durable Object classes so they stay available if the
// incremental cache / queue bindings are ever enabled in wrangler.jsonc.
export { DOQueueHandler, DOShardedTagCache, BucketCachePurge } from "../.open-next/worker.js";
